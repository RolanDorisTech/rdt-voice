namespace fs = std::filesystem;
static constexpr std::size_t kMaxLine = 64 * 1024;
static constexpr std::size_t kMaxQueue = 4;
static constexpr std::uint64_t kMaxWavBytes = 2ULL * 1024 * 1024 * 1024;

struct Command { std::string line; };
static std::mutex g_queue_mutex;
static std::condition_variable g_queue_cv;
static std::queue<Command> g_queue;
static bool g_reader_done = false;
static std::atomic_bool g_shutdown{false};
static std::atomic_bool g_cancel{false};
static std::mutex g_active_mutex;
static std::string g_active_id;
// IDs are registered before queue insertion; queued cancellation must not be lost.
static std::unordered_set<std::string> g_known_request_ids;
static std::unordered_set<std::string> g_cancel_requested_ids;

static std::string architecture_name() {
#if defined(_M_ARM64) || defined(__aarch64__)
    return "arm64";
#elif defined(_M_X64) || defined(__x86_64__)
    return "x64";
#elif defined(_M_IX86) || defined(__i386__)
    return "x86";
#else
    return "unknown";
#endif
}

static int b64_value(char c) {
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= 'a' && c <= 'z') return c - 'a' + 26;
    if (c >= '0' && c <= '9') return c - '0' + 52;
    if (c == '-' || c == '+') return 62;
    if (c == '_' || c == '/') return 63;
    return -1;
}
static bool b64_decode(const std::string &in, std::string &out) {
    if (in.size() > kMaxLine || in.size() % 4 == 1) return false;
    std::uint32_t acc = 0; int bits = 0;
    out.clear(); out.reserve(in.size() * 3 / 4);
    for (char c : in) {
        if (c == '=') break;
        int v = b64_value(c); if (v < 0) return false;
        acc = (acc << 6) | static_cast<unsigned>(v); bits += 6;
        if (bits >= 8) { bits -= 8; out.push_back(static_cast<char>((acc >> bits) & 0xff)); }
        if (out.size() > kMaxLine) return false;
    }
    return true;
}
static std::string b64_encode(const std::string &in) {
    static constexpr char table[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
    std::string out; std::uint32_t acc = 0; int bits = 0;
    out.reserve((in.size() * 4 + 2) / 3);
    for (unsigned char c : in) {
        acc = (acc << 8) | c; bits += 8;
        while (bits >= 6) { bits -= 6; out.push_back(table[(acc >> bits) & 63]); }
    }
    if (bits) out.push_back(table[(acc << (6 - bits)) & 63]);
    return out;
}
static std::vector<std::string> split_tabs(const std::string &line) {
    std::vector<std::string> parts; std::size_t start = 0;
    for (;;) {
        auto pos = line.find('\t', start);
        if (pos == std::string::npos) { parts.emplace_back(line.substr(start)); break; }
        parts.emplace_back(line.substr(start, pos - start)); start = pos + 1;
        if (parts.size() > 8) break;
    }
    return parts;
}
static bool abort_callback(void *user_data) {
    auto *flag = static_cast<std::atomic_bool *>(user_data);
    return flag && flag->load(std::memory_order_relaxed);
}

// Accept only PCM16 mono/16 kHz WAV generated by the private backend temp pipeline.
static bool read_pcm16_wav(const fs::path &path, std::vector<float> &samples, std::string &code) {
    std::error_code ec;
    if (!fs::is_regular_file(path, ec) || ec || fs::file_size(path, ec) > kMaxWavBytes || ec) { code = "audio_file_invalid"; return false; }
    std::ifstream stream(path, std::ios::binary);
    if (!stream) { code = "audio_file_unreadable"; return false; }
    char riff[4], wave[4]; std::uint32_t riff_size = 0;
    stream.read(riff, 4); stream.read(reinterpret_cast<char *>(&riff_size), 4); stream.read(wave, 4);
    if (!stream || std::memcmp(riff, "RIFF", 4) || std::memcmp(wave, "WAVE", 4)) { code = "audio_wav_invalid"; return false; }
    bool have_fmt = false, have_data = false; std::uint16_t format = 0, channels = 0, bits = 0;
    std::uint32_t rate = 0, data_size = 0; std::streampos data_pos{};
    while (stream && !(have_fmt && have_data)) {
        char tag[4]; std::uint32_t len = 0;
        stream.read(tag, 4); stream.read(reinterpret_cast<char *>(&len), 4);
        if (!stream || len > kMaxWavBytes) break;
        auto chunk_pos = stream.tellg();
        if (!std::memcmp(tag, "fmt ", 4)) {
            std::uint32_t byte_rate = 0; std::uint16_t align = 0;
            stream.read(reinterpret_cast<char *>(&format), 2);
            stream.read(reinterpret_cast<char *>(&channels), 2);
            stream.read(reinterpret_cast<char *>(&rate), 4);
            stream.read(reinterpret_cast<char *>(&byte_rate), 4);
            stream.read(reinterpret_cast<char *>(&align), 2);
            stream.read(reinterpret_cast<char *>(&bits), 2);
            if (!stream || len < 16) { code = "audio_wav_fmt_invalid"; return false; }
            have_fmt = true;
        } else if (!std::memcmp(tag, "data", 4)) {
            data_pos = chunk_pos; data_size = len; have_data = true;
        }
        stream.clear(); stream.seekg(chunk_pos + static_cast<std::streamoff>(len + (len & 1U)));
    }
    if (!have_fmt || !have_data || format != 1 || channels != 1 || rate != 16000 || bits != 16 || data_size < 2 || (data_size & 1U)) {
        code = "audio_wav_format_unsupported"; return false;
    }
    samples.resize(data_size / 2);
    stream.clear(); stream.seekg(data_pos);
    constexpr std::size_t kReadChunkSamples = 32768;
    std::vector<std::int16_t> raw(std::min(samples.size(), kReadChunkSamples));
    for (std::size_t offset = 0; offset < samples.size();) {
        if (g_cancel.load(std::memory_order_relaxed)) { code = "cancelled"; samples.clear(); return false; }
        const std::size_t count = std::min(raw.size(), samples.size() - offset);
        stream.read(reinterpret_cast<char *>(raw.data()),
                    static_cast<std::streamsize>(count * sizeof(std::int16_t)));
        if (!stream) { code = "audio_wav_truncated"; samples.clear(); return false; }
        for (std::size_t i = 0; i < count; ++i) {
            samples[offset + i] = static_cast<float>(raw[i]) / 32768.0f;
        }
        offset += count;
    }
    if (g_cancel.load(std::memory_order_relaxed)) {
        code = "cancelled"; samples.clear(); return false;
    }
    return !samples.empty();
}

static bool valid_request_id(const std::string &id) {
    if (id.empty() || id.size() > 48) return false;
    for (unsigned char c : id) {
        const bool allowed = (c >= 'A' && c <= 'Z') ||
                             (c >= 'a' && c <= 'z') ||
                             (c >= '0' && c <= '9') ||
                             c == '_' || c == '-';
        if (!allowed) return false;
    }
    return true;
}

static void reader_thread() {
    std::string line;
    while (std::getline(std::cin, line)) {
        if (line.size() > kMaxLine) { g_shutdown.store(true); break; }
        auto fields = split_tabs(line);
        if (!fields.empty() && fields[0] == "CANCEL" && fields.size() == 2) {
            std::lock_guard<std::mutex> lock(g_active_mutex);
            if (fields[1] == g_active_id) {
                g_cancel.store(true, std::memory_order_relaxed);
            } else if (g_known_request_ids.find(fields[1]) != g_known_request_ids.end()) {
                // The command may be queued but not active yet. Keep the cancel
                // scoped to that registered request until its processing begins.
                g_cancel_requested_ids.insert(fields[1]);
            }
            continue;
        }
        if (!fields.empty() && fields[0] == "SHUTDOWN") {
            g_shutdown.store(true); g_cancel.store(true); g_queue_cv.notify_all(); break;
        }
        const auto command_fields = split_tabs(line);
        if (command_fields.size() == 4 && command_fields[0] == "TRANSCRIBE"
                && valid_request_id(command_fields[1])) {
            bool duplicate_request = false;
            {
                std::lock_guard<std::mutex> lock(g_active_mutex);
                duplicate_request =
                    g_known_request_ids.find(command_fields[1]) != g_known_request_ids.end();
                if (!duplicate_request) g_known_request_ids.insert(command_fields[1]);
            }
            if (duplicate_request) {
                // Duplicate outstanding IDs make request-scoped cancellation ambiguous.
                g_shutdown.store(true);
                g_cancel.store(true, std::memory_order_relaxed);
                g_queue_cv.notify_all();
                break;
            }
        }
        {
            std::lock_guard<std::mutex> lock(g_queue_mutex);
            if (g_queue.size() >= kMaxQueue) { g_shutdown.store(true); break; }
            g_queue.push(Command{std::move(line)});
        }
        g_queue_cv.notify_one();
    }
    { std::lock_guard<std::mutex> lock(g_queue_mutex); g_reader_done = true; }
    g_queue_cv.notify_all();
}

static void finish_request(const std::string &id) {
    std::lock_guard<std::mutex> lock(g_active_mutex);
    if (g_active_id == id) g_active_id.clear();
    g_cancel_requested_ids.erase(id);
    g_known_request_ids.erase(id);
}

static bool transcribe(struct whisper_context *ctx, const std::vector<std::string> &f) {
    if (f.size() != 4 || f[0] != "TRANSCRIBE" || !valid_request_id(f[1])) {
        std::cout << "ERROR\t0\trequest_invalid" << std::endl; return false;
    }
    const std::string id = f[1]; std::string language, path_bytes;
    if (!b64_decode(f[2], language) || language.size() > 48 || !b64_decode(f[3], path_bytes) || path_bytes.empty() || path_bytes.size() > 32768) {
        finish_request(id);
        std::cout << "ERROR\t" << id << "\trequest_invalid" << std::endl; return false;
    }
    {
        std::lock_guard<std::mutex> lock(g_active_mutex);
        g_active_id = id;
        const bool cancel_before_activation = g_cancel_requested_ids.erase(id) > 0;
        const bool shutting_down = g_shutdown.load(std::memory_order_relaxed);
        g_cancel.store(cancel_before_activation || shutting_down,
                       std::memory_order_relaxed);
    }
    fs::path wav = fs::u8path(path_bytes.begin(), path_bytes.end());
    std::vector<float> pcm; std::string error;
    if (!read_pcm16_wav(wav, pcm, error)) {
        finish_request(id);
        std::cout << "ERROR\t" << id << "\t" << error << std::endl;
        return false;
    }
    whisper_full_params params = whisper_full_default_params(WHISPER_SAMPLING_GREEDY);
    params.print_progress = false; params.print_realtime = false; params.print_timestamps = false;
    params.no_context = true; params.temperature = 0.0f; params.n_threads = std::max(1, std::min(16, static_cast<int>(std::thread::hardware_concurrency())));
    params.language = (language.empty() || language == "auto") ? "auto" : language.c_str();
    params.translate = false; params.abort_callback = abort_callback; params.abort_callback_user_data = &g_cancel;
    const int result = whisper_full(ctx, params, pcm.data(), static_cast<int>(pcm.size()));
    if (result != 0) {
        const bool cancelled = g_cancel.load(std::memory_order_relaxed);
        std::cout << "ERROR\t" << id << "\t" << (cancelled ? "cancelled" : "inference_failed") << std::endl;
    } else {
        const int count = whisper_full_n_segments(ctx);
        for (int i = 0; i < count; ++i) {
            const char *text = whisper_full_get_segment_text(ctx, i);
            const std::int64_t start = whisper_full_get_segment_t0(ctx, i);
            const std::int64_t end = whisper_full_get_segment_t1(ctx, i);
            std::string segment = text ? text : "";
            const std::int64_t safe_start = std::max<std::int64_t>(0, start);
            const std::int64_t safe_end = std::max<std::int64_t>(safe_start, end);
            std::cout << "SEGMENT\t" << id << '\t' << safe_start << '\t'
                      << safe_end << '\t' << b64_encode(segment) << std::endl;
        }
        const int lang_id = whisper_full_lang_id(ctx);
        const char *lang_name = lang_id >= 0 ? whisper_lang_str(lang_id) : nullptr;
        std::cout << "DONE\t" << id << '\t' << (lang_name ? b64_encode(lang_name) : "-") << std::endl;
    }
    finish_request(id);
    return result == 0;
}


struct ProviderInfo {
    std::string provider;
    std::string device;
};

static bool select_provider(ProviderInfo &out) {
#if defined(RDT_ENABLE_CUDA) && RDT_ENABLE_CUDA
    const char *registry_name = "CUDA";
    const char *provider_name = "CUDA";
#elif defined(RDT_ENABLE_VULKAN) && RDT_ENABLE_VULKAN
    const char *registry_name = "Vulkan";
    const char *provider_name = "Vulkan";
#else
    out.provider = "CPU";
    out.device = "CPU";
    return true;
#endif

#if (defined(RDT_ENABLE_CUDA) && RDT_ENABLE_CUDA) || (defined(RDT_ENABLE_VULKAN) && RDT_ENABLE_VULKAN)
    ggml_backend_reg_t reg = ggml_backend_reg_by_name(registry_name);
    if (!reg) return false;

    ggml_backend_dev_t selected = nullptr;
    for (auto wanted_type : {GGML_BACKEND_DEVICE_TYPE_GPU, GGML_BACKEND_DEVICE_TYPE_IGPU}) {
        for (size_t i = 0; i < ggml_backend_reg_dev_count(reg); ++i) {
            ggml_backend_dev_t dev = ggml_backend_reg_dev_get(reg, i);
            if (dev && ggml_backend_dev_type(dev) == wanted_type) {
                selected = dev;
                break;
            }
        }
        if (selected) break;
    }
    if (!selected) return false;

    const char *description = ggml_backend_dev_description(selected);
    const char *name = ggml_backend_dev_name(selected);
    out.provider = provider_name;
    out.device = (description && *description) ? description :
                 ((name && *name) ? name : provider_name);
    std::replace(out.device.begin(), out.device.end(), '\t', ' ');
    std::replace(out.device.begin(), out.device.end(), '\r', ' ');
    std::replace(out.device.begin(), out.device.end(), '\n', ' ');
    return true;
#endif
    return false;
}

int main(int argc, char **argv) {
    fs::path model;
    for (int i = 1; i < argc; ++i) {
        if (std::string(argv[i]) == "--model" && i + 1 < argc) model = fs::u8path(argv[++i]);
        else { std::cerr << "invalid_argument"; return 2; }
    }
    if (model.empty()) { std::cerr << "model_required"; return 2; }
    ProviderInfo provider;
    if (!select_provider(provider)) {
        std::cerr << "requested_gpu_backend_has_no_usable_device" << std::endl;
        return 4;
    }
    struct whisper_context_params cparams = whisper_context_default_params();
#if (defined(RDT_ENABLE_CUDA) && RDT_ENABLE_CUDA) || (defined(RDT_ENABLE_VULKAN) && RDT_ENABLE_VULKAN)
    cparams.use_gpu = true;
#else
    cparams.use_gpu = false;
#endif
    struct whisper_context *ctx = whisper_init_from_file_with_params(model.u8string().c_str(), cparams);
    if (!ctx) { std::cerr << "model_load_failed"; return 3; }
    std::cout << "READY\t" << architecture_name() << "\twhisper.cpp/v1.9.5\t"
              << provider.provider << "\t" << provider.device << std::endl;
    std::thread input(reader_thread);
    for (;;) {
        Command cmd;
        {
            std::unique_lock<std::mutex> lock(g_queue_mutex);
            g_queue_cv.wait(lock, [] { return !g_queue.empty() || g_reader_done || g_shutdown.load(); });
            if (g_shutdown.load() && g_queue.empty()) break;
            if (g_queue.empty()) { if (g_reader_done) break; else continue; }
            cmd = std::move(g_queue.front()); g_queue.pop();
        }
        auto fields = split_tabs(cmd.line);
        transcribe(ctx, fields);
        if (g_shutdown.load()) break;
    }
    g_shutdown.store(true); g_cancel.store(true); g_queue_cv.notify_all();
    if (input.joinable()) input.join();
    whisper_free(ctx);
    return 0;
}
